"""Project costs downloads (Change 12, D-171): the Excel workbook and the CSV of the Detail.

Layout only — every amount comes from the CostReport (project_costs.py) the page shows, so the
files always match it. Money is exact (Decimal) and shown as USD in Excel; text cells are
spreadsheet-safe (safe_cell, D-68); no salaries and no reasons. Each download writes one
EXPORT audit row with the filters and the row count, never the data.
"""

import csv
import io

from django.utils import timezone
from openpyxl import Workbook

from apps.audit.models import AuditLog
from apps.audit.services.log import record
from apps.payroll.services.export import safe_cell
from apps.projects.services.tasks import TASK_NOT_RECORDED
from apps.reports.services.project_costs import NOTES, RATE_MISSING
from apps.reports.services.project_report import hours
from apps.reports.services.report_files import sheet
from apps.timesheets.services.calendar import company_tz

DETAIL_COLUMNS = (  # (heading, value, kind) — one row per Project-work entry
    ("date", lambda r: r.detail.work_date.isoformat(), "text"),
    ("week_start", lambda r: r.detail.week_start.isoformat(), "text"),
    ("employee_code", lambda r: r.detail.person.employee.employee_code, "text"),
    ("employee_name", lambda r: r.detail.person.name, "text"),
    ("team", lambda r: r.detail.person.team, "text"),
    ("manager", lambda r: r.detail.person.manager, "text"),
    ("project_code", lambda r: r.detail.project.code, "text"),
    ("project_name", lambda r: r.detail.project.name, "text"),
    ("task_code", lambda r: r.detail.task.code if r.detail.task else "", "text"),
    ("task_name", lambda r: r.detail.task.name if r.detail.task else TASK_NOT_RECORDED, "text"),
    ("charge_code", lambda r: r.detail.charge_code, "text"),
    ("hours", lambda r: hours(r.detail.minutes), "hours"),
    ("pay_type", lambda r: r.pay_type, "text"),
    ("hourly_rate", lambda r: r.rate, "money"),
    ("cost", lambda r: r.cost, "money"),
    ("rate_missing", lambda r: "yes" if r.pay is None else "", "text"),
)
HOUR_HEADINGS = {
    "Hours",
    "Hours without pay rate",
    "Own group: hours",
    "Including everyone below: hours",
    "hours",
    "% used",
}


def file_name(report, extension):
    f = report.filters
    return f"project-costs_{f.start.isoformat()}_to_{f.end.isoformat()}.{extension}"


def audit_download(report, fmt, rows):
    f = report.filters
    return record(
        AuditLog.Action.EXPORT,
        "ProjectCosts",
        f"{f.start.isoformat()}..{f.end.isoformat()}",
        actor=report.viewer,
        after={"format": fmt, "filters": f.query(True), "rows": rows},
    )


def detail_csv(report):
    """The Detail as CSV text (the caller adds the byte-order mark)."""
    out = io.StringIO()
    writer = csv.writer(out)
    writer.writerow([name for name, _, _ in DETAIL_COLUMNS])
    for r in report.rows:
        cells = []
        for _, value, kind in DETAIL_COLUMNS:
            v = value(r)
            if kind == "hours":
                cells.append(f"{v:.2f}")
            elif kind == "money":
                cells.append("" if v is None else f"{v:.2f}")
            else:
                cells.append(safe_cell(v))
        writer.writerow(cells)
    return out.getvalue()


def tabs(report):
    """The tabs, as on the page (D-171): a group tab only where it changes something (D-165)."""
    groups = report.filters.groups
    names = ["Summary", "By project"]
    names += [n for n, g in (("By team", "team"), ("By manager", "manager")) if g in groups]
    names += ["By task", "By pay type", "By pay period", "By employee", "Detail"]
    return names + (["Rate missing"] if report.missing else [])


def _summary(report):
    viewer = report.viewer
    generated = timezone.now().astimezone(company_tz())
    described = [(k, v) for k, v in report.filters.described(True) if k != "Hours"]
    rows = [
        ("Report", "Project costs"),
        ("Generated at", generated.strftime("%Y-%m-%d %H:%M %Z")),
        ("Generated by", f"{viewer.first_name} {viewer.last_name} ({viewer.employee_code})"),
        *described,
        ("Hours", "Approved only"),
        ("Project hours", hours(report.minutes)),
        ("Labour cost", report.cost),
        ("Hours without a pay rate (not costed)", hours(report.unpriced)),
        ("Projects", len(report.by_project)),
        *(("Note", note) for note in NOTES),
    ]
    return ["Item", "Value"], rows, ("Value",)


def _by_project(report):
    header = [
        "I-code", "Project", "Budget", "Total cost to date", "Remaining", "% used", "Status",
        "Cost this period", "Hours this period", "Hours without pay rate (whole project)",
    ]  # fmt: skip
    rows = [
        (
            p.project.code,
            p.project.name,
            p.budget if p.budget is not None else "No budget set",
            p.total_cost,
            p.remaining if p.remaining is not None else "",
            float(p.used) if p.used is not None else "",
            p.status,
            p.cost,
            hours(p.minutes),
            hours(p.total_unpriced),
        )
        for p in report.by_project
    ]
    return (
        header,
        rows,
        HOUR_HEADINGS | {"Hours this period", "Hours without pay rate (whole project)"},
    )


def _groups(groups, label):
    header = [label, "People", "Hours", "Cost"]
    return header, [(g.label, g.people, hours(g.project), g.cost) for g in groups], HOUR_HEADINGS


def _by_manager(report):
    header = [
        "Manager", "Level", "People", "Own group: hours", "Own group: cost",
        "Including everyone below: hours", "Including everyone below: cost",
    ]  # fmt: skip
    rows = [
        (g.label, g.depth + 1 if g.employee else "", g.people, hours(g.project), g.cost,
         hours(g.rollup_project), g.rollup_cost)
        for g in report.by_manager
    ]  # fmt: skip
    return header, rows, HOUR_HEADINGS


def _lines(lines, label):
    header = [label, "Hours", "Cost", "Hours without pay rate"]
    rows = [(line.label, hours(line.minutes), line.cost, hours(line.unpriced)) for line in lines]
    return header, rows, HOUR_HEADINGS


def _by_employee(report):
    header = [
        "Employee code", "Name", "Status", "Team", "Manager", "Pay type", "Hourly rate",
        "Hours", "Cost", "Hours without pay rate",
    ]  # fmt: skip
    rows = []
    for p in report.people:
        types, rates = report.pay_used.get(p.employee.pk, ([], []))
        rate = rates[0] if len(rates) == 1 else " / ".join(f"${r:,.2f}" for r in rates)
        rows.append(
            (p.employee.employee_code, p.name, "Inactive" if p.inactive else "Active", p.team,
             p.manager, " / ".join(types) or RATE_MISSING, rate, hours(p.project), p.cost,
             hours(p.unpriced))
        )  # fmt: skip
    return header, rows, HOUR_HEADINGS


def _detail(report):
    header = [name for name, _, _ in DETAIL_COLUMNS]
    rows = [
        tuple(value(r) if value(r) is not None else "" for _, value, _ in DETAIL_COLUMNS)
        for r in report.rows
    ]
    return header, rows, HOUR_HEADINGS


def _missing(report):
    header = ["Employee code", "Name", "Team", "Manager", "Hours", "Dates"]
    rows = [
        (m.person.employee.employee_code, m.person.name, m.person.team, m.person.manager,
         hours(m.minutes), ", ".join(d.isoformat() for d in sorted(m.dates)))
        for m in report.missing
    ]  # fmt: skip
    return header, rows, HOUR_HEADINGS


def workbook(report):
    """The .xlsx bytes (D-171)."""
    book = Workbook(write_only=True)
    makers = {
        "Summary": lambda: _summary(report),
        "By project": lambda: _by_project(report),
        "By team": lambda: _groups(report.by_team, "Team"),
        "By manager": lambda: _by_manager(report),
        "By task": lambda: _lines(report.by_task, "Task"),
        "By pay type": lambda: _lines(report.by_pay_type, "Pay type"),
        "By pay period": lambda: _lines(report.by_pay_period, "Pay period"),
        "By employee": lambda: _by_employee(report),
        "Detail": lambda: _detail(report),
        "Rate missing": lambda: _missing(report),
    }
    for title in tabs(report):
        sheet(book, title, *makers[title]())
    out = io.BytesIO()
    book.save(out)
    return out.getvalue()
